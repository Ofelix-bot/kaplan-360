// Builds the /careers art from the approved drawings (plan §C, Q31–Q35): the 57 role scenes and the 16 industry
// heads become React components, lib/careers/art.ts maps each role to its scene, and the scenes' own keyframes
// go into app/[lang]/careers/careers.css between the build-art markers.
//
// Input (the drawing folder, ANIM):
//   parts/role-<scene>.html   one <div class="scene s" style="--p:#…"><svg viewBox="0 0 320 132">…</svg></div>,
//                             sometimes with one <style> holding a keyframe of its own
//   parts/head-<industry>.html one <svg class="la" viewBox="0 0 560 400">…</svg>
//   proto.html                the approved sample; its .ihead svg is the built-environment head
//   scenes.json               role id → scene id, for every role in data/raw/careers-roles.json
//
// Output:
//   components/careers/art/scenes/<scene>.tsx + index.ts   one lazy component per scene (next/dynamic)
//   components/careers/art/heads/<industry>.tsx + index.ts one lazy component per head
//   lib/careers/art.ts                                     ROLE_SCENE, SCENE_TINT, INDUSTRY_HEADS
//   app/[lang]/careers/careers.css                         the scenes' own keyframes, between the markers
//
// Every class in a scene gets the "rs-" prefix, so nothing meets the site's or Tailwind's classes; the heads keep
// the line-art classes (.la .f1 …, app/globals.css "Line art"). Literal colours that follow the theme become
// tokens (moved into style, since an SVG attribute can't hold var()). Rerun it whenever a drawing changes:
//
//   node scripts/careers/build-art.mjs [<ANIM folder>]

