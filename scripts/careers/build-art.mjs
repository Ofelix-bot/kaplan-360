// HTML attribute → JSX prop, where they differ.
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const KEEP = new Set(["viewBox", "pathLength", "role"]);
const propName = (a) => (a === "class" ? "className" : a.startsWith("aria-") || a.startsWith("data-") || KEEP.has(a) ? a : camel(a));

const pascal = (id) => id.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join("");

/** A style attribute as a JSX object literal. */
function styleObject(text, extra = {}) {
  const entries = [];
  for (const decl of text.split(";")) {
    const i = decl.indexOf(":");
    if (i < 0) continue;
    const k = decl.slice(0, i).trim();
    const v = decl.slice(i + 1).trim();
    if (!k) continue;
    entries.push([k.startsWith("--") ? k : camel(k), v]);
  }
  for (const [k, v] of Object.entries(extra)) entries.push([k, v]);
  if (entries.length === 0) return null;
  return `{{ ${entries.map(([k, v]) => `${/^[a-zA-Z]\w*$/.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)}`).join(", ")} }}`;
}

/**
 * One drawing (markup without comments or <style>) as JSX. `classes` maps a class token to its output name;
 * `ids` lists the ids the drawing defines, which become unique per instance (`${uid}-…`).
 */
function toJsx(markup, { classes, ids, themed }) {
  const idRef = (v) => {
    for (const id of ids) v = v.replaceAll(`url(#${id})`, `url(#\${uid}-${id})`);
    return v;
  };
  return markup.replace(/<([a-zA-Z][\w:-]*)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g, (_, tag, attrText, self) => {
    const props = [];
    let style = null;
    const moved = {};
    for (const [, name, value] of attrText.matchAll(/([\w:-]+)="([^"]*)"/g)) {
      if (name === "style") style = value;
      else if (name === "class") props.push(`className="${value.split(/\s+/).filter(Boolean).map(classes).join(" ")}"`);
      else if (name === "id") props.push(ids.includes(value) ? `id={\`\${uid}-${value}\`}` : `id="${value}"`);
      else if ((name === "fill" || name === "stroke") && themed && THEMED[value.toLowerCase()]) moved[name] = THEMED[value.toLowerCase()];
      else if (value.includes("url(#") && ids.length) props.push(`${propName(name)}={\`${idRef(value)}\`}`);
      else props.push(`${propName(name)}="${value}"`);
    }
    if (tag === "svg") {
      // Decorative: the heading beside it says what it shows.
      for (let i = props.length - 1; i >= 0; i--) if (/^(role|aria-label|aria-hidden)=/.test(props[i])) props.splice(i, 1);
      props.push(`aria-hidden="true"`, `focusable="false"`);
    }
    const so = style !== null || Object.keys(moved).length ? styleObject(style ?? "", moved) : null;
    if (so) props.push(`style=${so}`);
    return `<${tag}${props.length ? " " + props.join(" ") : ""}${self ? " /" : ""}>`;
  });
}

const stripComments = (s) => s.replace(/<!--[\s\S]*?-->/g, "");

/** A drawing's own <style> blocks, with every class and keyframe prefixed, the sample's curve as the site token. */
function prefixCss(css) {
  const frames = [...css.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]);
  let out = css.replace(/\.([a-zA-Z][\w-]*)/g, `.${PREFIX}$1`);
  for (const f of frames) out = out.replace(new RegExp(`(?<![\\w.-])${f}(?![\\w-])`, "g"), PREFIX + f);
  return out.replaceAll("var(--ui)", "var(--motion-ui)");
}

const reindent = (block, pad) =>
  block
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => pad + l)
    .join("\n");

function component({ name, jsx, src, ids }) {
  const indented = jsx
    .split("\n")
    .map((l) => l.trimEnd())
    .filter((l) => l.trim())
    .map((l) => "    " + l.trim())
    .join("\n");
  const body = ids.length
    ? `  // The drawing's ids (a clip path) are made unique per card, since several can be on one page.\n  const uid = useId().replace(/[^\\w-]/g, "");\n`
    : "";
  return `${HEADER(src)}${ids.length ? `import { useId } from "react";\n` : ""}\nexport default function ${name}() {\n${body}  return (\n${indented}\n  );\n}\n`;
}

function writeIndex(dir, ids, exportName, comment) {
  const lines = ids.map((id) => `  ${JSON.stringify(id)}: dynamic(() => import("./${id}")),`).join("\n");
  writeFileSync(
    join(dir, "index.ts"),
    `${HEADER("the drawing folder")}// ${comment}\n\nimport type { ComponentType } from "react";\nimport dynamic from "next/dynamic";\n\nexport const ${exportName}: Record<string, ComponentType> = {\n${lines}\n};\n`,
  );
}

const fresh = (dir) => {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
};

// ── role scenes ───────────────────────────────────────────────────────────────────────────────────────────

const sceneDir = join(ART, "scenes");
fresh(sceneDir);
const sceneFiles = readdirSync(PARTS).filter((f) => /^role-.+\.html$/.test(f)).sort();
const tints = {};
const sceneCss = [];
for (const f of sceneFiles) {
  const id = f.slice(5, -5);
  let html = stripComments(readFileSync(join(PARTS, f), "utf8"));
  for (const m of html.matchAll(/<style>([\s\S]*?)<\/style>/g)) sceneCss.push(`/* ${id} */\n` + prefixCss(m[1]));
  html = html.replace(/<style>[\s\S]*?<\/style>/g, "");
  const tint = html.match(/<div class="scene s" style="--p:\s*(#[0-9a-fA-F]{6})"/)?.[1]?.toLowerCase();
  if (!tint || !TINTS[tint]) throw new Error(`${f}: the panel tint is missing or not one of ${Object.keys(TINTS).join(", ")}`);
  tints[id] = TINTS[tint];
  const svg = html.match(/<svg[\s\S]*<\/svg>/)?.[0];
  if (!svg) throw new Error(`${f}: no <svg>`);
  const ids = [...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  const jsx = toJsx(svg, { classes: (c) => PREFIX + c, ids, themed: true });
  writeFileSync(join(sceneDir, `${id}.tsx`), component({ name: `${pascal(id)}Scene`, jsx, src: `parts/${f}`, ids }));
}
const sceneIds = sceneFiles.map((f) => f.slice(5, -5));
writeIndex(sceneDir, sceneIds, "SCENES", "One lazy component per role scene, so a page loads only the scenes it shows.");

// ── industry heads ────────────────────────────────────────────────────────────────────────────────────────

